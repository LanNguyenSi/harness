/**
 * Thrown instead of a plain `Error` when the install refuses rather than
 * guesses (a duplicate/moved BEGIN marker, or a foreign table wedged
 * inside the managed block). Extends `HarnessExitError` so it carries the
 * repo's own exit-code convention (`EX_FAIL`) through `run()`'s top-level
 * catch without the generic "return 70" branch, and the CLI action can
 * recognize it by type to emit a structured `--json` error the same way
 * the other apply refusals (`target-exists-refuse`, `drift-refuse`) do.
 */
export class CodexInstallRefusalError extends HarnessExitError {
  constructor(
    message: string,
    public readonly configPath: string,
  ) {
    super(message, EX_FAIL);
    this.name = "CodexInstallRefusalError";
  }
}

const GENERATED_HEADER = "# Generated by harness apply --runtime codex.";
const LEGACY_HOOK_TABLE_RE =
  /^\[\[hooks\.(pre_tool_use|post_tool_use|user_prompt_submit|session_start|stop)\]\]$/;
const CURRENT_HOOK_TABLE_RE = /^\[\[hooks\.[A-Za-z][A-Za-z0-9_]*\]\]$/;
// A single, unquoted-or-quoted TOML bare/quoted key: `foo-bar_1`, a basic
// `"..."` string (escapes allowed), or a literal `'...'` string (no
// escapes, so a literal key may itself contain `[`, `]`, `"` or `#`
// verbatim, e.g. `'a[b'`).
const TOML_KEY = String.raw`(?:[A-Za-z0-9_-]+|"(?:[^"\\]|\\.)*"|'[^']*')`;
// A single-line TOML table header only: `[key]`, `[[key]]`, or a dotted
// path of keys (`[a.b."c d".'e[f']`), optionally surrounded by whitespace
// around the brackets and each dot, and optionally followed by whitespace
// and a trailing comment. Quote-aware so a key that itself contains `[`,
// `]`, `.` or `#` (a real path or filename used as a TOML key, e.g.
// `[projects."/Users/x/Photos [2024]"]`, `[plugins.'a[b']`) is still
// recognized as one header, instead of the bracket/hash inside the quotes
// being mistaken for the header's own delimiters. Deliberately excludes an
// array-continuation line such as `  [1, 2],` (no trailing comma allowed,
// and a bare numeric-looking segment such as `1` only ever matches as a
// single key with nothing after it, never as an array element) so a
// multi-line array/value sitting inside a still-owned harness hook table
// is never misread as a foreign table header ending the owned region
// early (task 6a037359).
const NON_HOOK_TABLE_RE = new RegExp(
  String.raw`^\[(?!\[hooks\.)\[?\s*${TOML_KEY}(?:\s*\.\s*${TOML_KEY})*\s*\]\]?\s*(?:#.*)?$`,
);
// Every emitted hook table is preceded by exactly this comment shape
// (generate-codex-config.ts's `emitHook`); used both to name removed hook
// blocks in the install summary and to detect a foreign table wedged
// between two harness hook tables (see `assertNoSplitBlock`).
const HARNESS_HOOK_COMMENT_PREFIX = "# harness hook: ";
const HOOK_ID_LINE_RE = /^# harness hook: (.+) \(budget_ms=\d+\)$/;

