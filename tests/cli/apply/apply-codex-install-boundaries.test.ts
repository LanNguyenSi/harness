function write(lines: string[]): string {
  const body = lines.join("\n");
  fs.writeFileSync(codexConfig, body);
  return body;
}

function plan(generatedContent = FRESH) {
  return planCodexConfigInstall({ configPath: codexConfig, generatedPath: "/x/config.toml", generatedContent });
}

/** The refusal the plan throws for the config on disk, or fails the test. */
function refusal(): CodexInstallRefusalError {
  try {
    plan();
  } catch (err) {
    expect(err).toBeInstanceOf(CodexInstallRefusalError);
    return err as CodexInstallRefusalError;
  }
  throw new Error("expected the plan to refuse");
}

/** Plans over the config on disk, writes the result, plans again: the second
 * plan must change nothing. Returns the first plan. */
function planTwice() {
  const first = plan();
  fs.writeFileSync(codexConfig, first.nextContent);
  const second = plan();
  expect(second.changed).toBe(false);
  expect(second.nextContent).toBe(first.nextContent);
  return first;
}

function count(haystack: string, needle: string): number {
  return haystack.split(needle).length - 1;
}

function endLines(text: string): number {
  return text.split(/\r?\n/).filter((l) => l.trim() === CODEX_MANAGED_END).length;
}

/** 1-based number of the first line of `text` whose trimmed text is `line`. */
function lineOf(text: string, line: string): number {
  return text.split("\n").findIndex((l) => l.trim() === line) + 1;
}

/** 1-based number of the last such line (a kept table sits after the fresh block). */
function lastLineOf(text: string, line: string): number {
  return text.split("\n").map((l) => l.trim()).lastIndexOf(line) + 1;
}

function keptLabel(header: string, before: string, after: string): string {
  return `${header} (line ${lineOf(before, header)} before the install, line ${lastLineOf(after, header)} after it)`;
}

/** Every hook command of the parsed config's `hooks.Stop` array. */
function stopCommands(text: string): string[] {
  const doc = parseTomlForTest(text) as {
    hooks?: { Stop?: Array<{ command?: string; hooks?: Array<{ command?: string }> }> };
  };
  return (doc.hooks?.Stop ?? []).flatMap((entry) => [
    ...(entry.command !== undefined ? [entry.command] : []),
    ...(entry.hooks ?? []).flatMap((h) => (h.command !== undefined ? [h.command] : [])),
  ]);
}

interface CliRun {
  code: number;
  out: string;
  err: string;
}

async function cli(opts: { json?: boolean; dryRun?: boolean }): Promise<CliRun> {
  let out = "";
  let err = "";
  const code = await run({
    argv: [
      "apply",
      "--config",
      manifestPath,
      "--runtime",
      "codex",
      "--install",
      "--codex-config",
      codexConfig,
      ...(opts.dryRun ? ["--dry-run"] : []),
      ...(opts.json ? ["--json"] : []),
    ],
    stdout: (s: string) => {
      out += s;
    },
    stderr: (s: string) => {
      err += s;
    },
  });
  return { code, out, err };
}

/** The CLI over the config on disk in every mode (--dry-run, --dry-run
 * --json, the install and its --json form), the config written back before
 * each run. */
async function everyMode(): Promise<CliRun[]> {
  const original = fs.readFileSync(codexConfig, "utf8");
  const runs: CliRun[] = [];
  for (const opts of [{ dryRun: true }, { dryRun: true, json: true }, {}, { json: true }]) {
    fs.writeFileSync(codexConfig, original);
    runs.push(await cli(opts));
  }
  fs.writeFileSync(codexConfig, original);
  return runs;
}

describe("codex install: boundary checks of the hook header map and the END line are exact (task e8f4fc03)", () => {
  it("a sub-table [[hooks.Stop.HOOKS]] of a kept entry with two inline hooks is not the nested hooks array: both tables are kept and named", () => {
    const config = write([
      CODEX_MANAGED_BEGIN,
      GENERATED,
      ...HARNESS_A,
      "[[hooks.Stop]]",
      `hooks = [{ type = "command", command = "${OPERATOR_COMMAND}", timeout = 5 }, { type = "command", command = "operator-second", timeout = 5 }]`,
      "[[hooks.Stop.HOOKS]]",
      "x = 1",
      CODEX_MANAGED_END,
      "",
    ]);
    const p = planTwice();
    expect(p.keptOperatorHookTables).toEqual([
      keptLabel("[[hooks.Stop]]", config, p.nextContent),
      keptLabel("[[hooks.Stop.HOOKS]]", config, p.nextContent),
    ]);
    expect(stopCommands(p.nextContent)).toEqual(["harness pack hook b", OPERATOR_COMMAND, "operator-second"]);
  });

  it('a table whose quoted root key only equals `hooks` after trimming ([[ " hooks" . Stop ]]) is outside `hooks`: the kept table is matched to its own entry', () => {
    const other = ['[[ " hooks" . Stop ]]', 'hooks = [{ type = "command", command = "archived-hook", timeout = 5 }]'];
    const config = write([
      ...other,
      CODEX_MANAGED_BEGIN,
      GENERATED,
      ...HARNESS_A,
      "[[hooks.Stop]]",
      `hooks = [{ type = "command", command = "${OPERATOR_COMMAND}", timeout = 5 }]`,
      CODEX_MANAGED_END,
      "",
    ]);
    const p = planTwice();
    expect(p.keptOperatorHookTables).toEqual([keptLabel("[[hooks.Stop]]", config, p.nextContent)]);
    expect(p.nextContent.startsWith(`${other.join("\n")}\n`)).toBe(true);
    expect(stopCommands(p.nextContent)).toEqual(["harness pack hook b", OPERATOR_COMMAND]);
  });

  it("a comment line that only starts with the END marker text does not end the block: one END is written and each harness hook once", () => {
    write([
      CODEX_MANAGED_BEGIN,
      GENERATED,
      ...HARNESS_A,
      `${CODEX_MANAGED_END} (the old block ended here)`,
      ...HARNESS_B,
      CODEX_MANAGED_END,
      '[projects."/work/x"]',
      'trust_level = "trusted"',
      "",
    ]);
    const p = planTwice();
    expect(endLines(p.nextContent)).toBe(1);
    expect(p.nextContent).not.toContain("(the old block ended here)");
    expect(count(p.nextContent, 'command = "harness pack hook a"')).toBe(1);
    expect(count(p.nextContent, 'command = "harness pack hook b"')).toBe(1);
    expect(p.nextContent.endsWith(`${CODEX_MANAGED_END}\n[projects."/work/x"]\ntrust_level = "trusted"\n`)).toBe(true);
  });

  it("past a foreign table, a comment line that only starts with the END marker text is not the drifted END: the real END is removed and the comment kept", () => {
    const comment = `${CODEX_MANAGED_END} (moved here by hand)`;
    write([CODEX_MANAGED_BEGIN, GENERATED, ...HARNESS_A, "[tui]", comment, "theme = 1", CODEX_MANAGED_END, ...TAIL, ""]);
    const p = planTwice();
    expect(endLines(p.nextContent)).toBe(1);
    expect(count(p.nextContent, comment)).toBe(1);
    expect(p.nextContent.endsWith(`${CODEX_MANAGED_END}\n[tui]\n${comment}\ntheme = 1\n${TAIL.join("\n")}\n`)).toBe(true);
  });

  it("the split-block refusal names the first harness marker line past the foreign table, whichever marker it is", () => {
    const config = write([
      CODEX_MANAGED_BEGIN,
      GENERATED,
      ...HARNESS_A,
      "[tui]",
      "theme = 1",
      ...HARNESS_B,
      "# Harness Codex hook wiring. Generated source: a later copy",
      "",
    ]);
    const { message } = refusal();
    expect(message).toContain("has a foreign table ([tui])");
    expect(message).toContain(`line ${lineOf(config, "# harness hook: b (budget_ms=2000)")} contains '# harness hook:'`);
  });
});

// Layouts in which a hook event table spelled without the `[[hooks.` prefix
// sits directly after the harness tables: `table` is spliced in there.
const RESPELLED_LAYOUTS: Array<{ label: string; hasEnd: boolean; build: (table: string[]) => string[] }> = [
  { label: "BEGIN, END after the table", hasEnd: true, build: (t) => [CODEX_MANAGED_BEGIN, GENERATED, ...HARNESS_A, ...t, CODEX_MANAGED_END, ""] },
  { label: "BEGIN, no END", hasEnd: false, build: (t) => [CODEX_MANAGED_BEGIN, GENERATED, ...HARNESS_A, ...t, ""] },
  { label: "legacy source prefix, no END", hasEnd: false, build: (t) => [SOURCE_PREFIX, GENERATED, ...HARNESS_A, ...t, ""] },
  { label: "legacy generated header, no END", hasEnd: false, build: (t) => [GENERATED, ...HARNESS_A, ...t, ""] },
  { label: "legacy source prefix, END after the table", hasEnd: true, build: (t) => [SOURCE_PREFIX, GENERATED, ...HARNESS_A, ...t, CODEX_MANAGED_END, ""] },
  { label: "legacy generated header, END after the table", hasEnd: true, build: (t) => [GENERATED, ...HARNESS_A, ...t, CODEX_MANAGED_END, ""] },
];

const RESPELLINGS = ["[[ hooks.Stop ]]", '[["hooks".Stop]]', "[[hooks . Stop]]"];

const respelledTable = (header: string, command: string): string[] => [
  header,
  `note = "${TOKEN}"`,
  `hooks = [{ type = "command", command = "${command}", timeout = 5 }]`,
];

describe("codex install: a hook event table spelled without the [[hooks. prefix directly after the harness tables is named and checked (task e8f4fc03)", () => {
  for (const layout of RESPELLED_LAYOUTS) {
    for (const spelling of RESPELLINGS) {
      it(`${layout.label}, ${spelling} holding a command harness writes: refuses naming the table and its line, file untouched, no value text`, () => {
        const config = write(layout.build(respelledTable(spelling, "harness pack hook b")));
        const { message } = refusal();
        expect(message).toContain(`has a hook table ${spelling} (line ${lineOf(config, spelling)})`);
        expect(message).toContain("whose command is one harness itself writes");
        expect(message).not.toContain("Restore the comment line");
        expect(message).toContain("Delete the table");
        expect(message.includes("move it below the")).toBe(layout.hasEnd);
        expect(message).not.toContain("pack hook b");
        expect(message).not.toContain(TOKEN);
        expect(fs.readFileSync(codexConfig, "utf8")).toBe(config);
      });

      it(`${layout.label}, ${spelling} holding an operator command: kept once, named once with both line numbers, installs idempotently`, () => {
        const config = write(layout.build(respelledTable(spelling, OPERATOR_COMMAND)));
        const p = planTwice();
        const label = keptLabel(spelling, config, p.nextContent);
        expect(p.keptOperatorHookTables).toEqual([label]);
        expect(p.foreignSectionsPreserved).toEqual([label]);
        expect(stopCommands(p.nextContent)).toEqual(["harness pack hook b", OPERATOR_COMMAND]);
        expect(endLines(p.nextContent)).toBe(1);
        expect(JSON.stringify([p.summary, p.removedHookIds, p.foreignSectionsPreserved])).not.toContain(TOKEN);
      });
    }
  }
});

