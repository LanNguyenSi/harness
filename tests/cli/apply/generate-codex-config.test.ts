import { describe, expect, it } from "vitest";
import {
  CODEX_GENERATED_HEADER_LINE,
  generateCodexConfig,
} from "../../../src/cli/apply/generate-codex-config.js";
import { parseManifest, type Manifest } from "../../../src/schema/index.js";

function manifest(extra: Record<string, unknown> = {}): Manifest {
  return parseManifest({
    version: 1,
    hooks: [
      {
        name: "policy-pack:branch-protection:pre-tool-use",
        event: "PreToolUse",
        match: "apply_patch",
        command: "harness pack hook branch-protection --runtime codex",
        blocking: "hard",
        budget_ms: 5000,
        description: "Codex blocker",
      },
      {
        name: "hand-user-prompt-submit",
        event: "UserPromptSubmit",
        command: "/usr/bin/true",
        blocking: false,
        budget_ms: 5000,
      },
    ],
    ...extra,
  });
}

describe("generateCodexConfig", () => {
  it("emits CODEX_GENERATED_HEADER_LINE as the first line (apply's recovery branch pin)", () => {
    // src/cli/apply/apply.ts:recoverMissingLastApplyContent detects a
    // harness-generated codex artefact by `onDisk.startsWith(CODEX_GENERATED_HEADER_LINE)`.
    // If the generator's banner ever drifts away from this literal,
    // recovery silently disables and post-migration codex applies start
    // refusing again. Pin the link explicitly so a banner re-word fails
    // here loud instead of in a future operator's dogfood.
    const { content } = generateCodexConfig(manifest());
    expect(content.startsWith(CODEX_GENERATED_HEADER_LINE)).toBe(true);
  });

  it("the header describes the wire format without citing a removed pack doc", () => {
    const { content } = generateCodexConfig(manifest());
    const header = content.split("\n").filter((l) => l.startsWith("#")).join("\n");
    expect(header).toContain("Wire format a hook command reads on stdin");
    expect(header).toContain("0 = allow, 2 = block");
    expect(header).toContain("{ hook_event_name?: string, session_id?: string");
    expect(header).not.toContain("understanding-before-execution");
    expect(header).not.toContain("adapter scripts");
  });

  it("emits a header banner and one TOML stanza per hook", () => {
    const { content, warnings } = generateCodexConfig(manifest());
    expect(warnings).toEqual([]);
    expect(content).toContain("Generated by harness apply --runtime codex");
    expect(content).toContain("[[hooks.PreToolUse]]");
    expect(content).toContain("[[hooks.UserPromptSubmit]]");
    expect(content).toContain(
      "# harness hook: policy-pack:branch-protection:pre-tool-use (budget_ms=5000)",
    );
    expect(content).toContain(
      'hooks = [{ type = "command", command = "harness pack hook branch-protection --runtime codex", timeout = 5 }]',
    );
    expect(content).toContain('matcher = "apply_patch"');
    expect(content).not.toContain("timeout_ms = ");
    expect(content).not.toContain("blocking = ");
    expect(content).not.toContain("name = ");
    expect(content).not.toContain("description = ");
  });

  it("emits Codex protocol event names as hook table keys", () => {
    const { content } = generateCodexConfig(
      parseManifest({
        version: 1,
        hooks: [
          {
            name: "stop-hook",
            event: "Stop",
            command: "/usr/bin/true",
            blocking: false,
            budget_ms: 1000,
          },
          {
            name: "session-start-hook",
            event: "SessionStart",
            command: "/usr/bin/true",
            blocking: false,
            budget_ms: 1000,
          },
          {
            name: "post-tool-hook",
            event: "PostToolUse",
            command: "/usr/bin/true",
            blocking: false,
            budget_ms: 1000,
          },
        ],
      }),
    );
    expect(content).toContain("[[hooks.Stop]]");
    expect(content).toContain("[[hooks.SessionStart]]");
    expect(content).toContain("[[hooks.PostToolUse]]");
    expect(content).not.toContain("[[hooks.stop]]");
    expect(content).not.toContain("[[hooks.session_start]]");
    expect(content).not.toContain("[[hooks.post_tool_use]]");
  });

  it("expands Claude-style tool names to Codex hook match aliases", () => {
    const { content } = generateCodexConfig(
      parseManifest({
        version: 1,
        hooks: [
          {
            name: "shell-guard",
            event: "PreToolUse",
            match: "Bash",
            command: "echo shell-guard",
            blocking: "hard",
            budget_ms: 1000,
          },
          {
            name: "mcp-guard",
            event: "PreToolUse",
            match: "mcp__agent-tasks__pull_requests_create",
            command: "echo mcp-guard",
            blocking: "hard",
            budget_ms: 1000,
          },
        ],
      }),
    );

    expect(content).toContain(
      'matcher = "Bash|shell|exec_command|functions.exec_command"',
    );
    expect(content).toContain(
      'matcher = "mcp__agent-tasks__pull_requests_create|mcp__agent-tasks__.pull_requests_create|mcp__agent_tasks__pull_requests_create|mcp__agent_tasks__.pull_requests_create"',
    );
    expect(content).toContain(
      "# harness hook: shell-guard (budget_ms=1000)",
    );
    // An ordinary command is emitted verbatim: no `--hook <name>` tag and
    // the generic 1 s floor.
    expect(content).toContain(
      'hooks = [{ type = "command", command = "echo shell-guard", timeout = 1 }]',
    );
    expect(content).not.toContain("--hook");
  });

  it("keeps the hook-name comment on one line when the name carries a newline or a control byte", () => {
    const { content } = generateCodexConfig(
      parseManifest({
        version: 1,
        hooks: [
          {
            name: "evil\n[[hooks.Stop]]\u0007x",
            event: "PreToolUse",
            command: "echo evil",
            blocking: false,
            budget_ms: 1000,
          },
        ],
      }),
    );
    expect(content).toContain("# harness hook: evil [[hooks.Stop]] x (budget_ms=1000)");
    expect(content).not.toMatch(/^\[\[hooks\.Stop\]\]/m);
    expect(content).not.toContain("\u0007");
  });

  it("emits a hook whose command is `echo shell-guard` verbatim, with the budget as its timeout", () => {
    // An ordinary command with a >=2000ms budget: the budget surfaces as
    // its own seconds value and the command text carries no `--hook` tag.
    const { content } = generateCodexConfig(
      parseManifest({
        version: 1,
        hooks: [
          {
            name: "shell-guard",
            event: "PreToolUse",
            match: "Bash",
            command: "echo shell-guard",
            blocking: "hard",
            budget_ms: 2000,
          },
        ],
      }),
    );
    expect(content).toContain(
      'hooks = [{ type = "command", command = "echo shell-guard", timeout = 2 }]',
    );
    expect(content).not.toContain("--hook");
  });

  it("converts manifest millisecond budgets to Codex timeout seconds", () => {
    const { content } = generateCodexConfig(
      parseManifest({
        version: 1,
        hooks: [
          {
            name: "round-up",
            event: "SessionStart",
            command: "/usr/bin/true",
            blocking: false,
            budget_ms: 1501,
          },
        ],
      }),
    );
    expect(content).toContain('command = "/usr/bin/true", timeout = 2');
  });

  it("keeps non-policy 1000ms hooks at Codex's 1s minimum", () => {
    const { content } = generateCodexConfig(
      parseManifest({
        version: 1,
        hooks: [
          {
            name: "fast-non-policy",
            event: "PreToolUse",
            command: "/usr/bin/true",
            blocking: false,
            budget_ms: 1000,
          },
        ],
      }),
    );
    expect(content).toContain('command = "/usr/bin/true", timeout = 1');
  });

  it("is byte-stable for a given manifest (regenerable on no-op apply)", () => {
    const a = generateCodexConfig(manifest()).content;
    const b = generateCodexConfig(manifest()).content;
    expect(a).toBe(b);
  });

  it("warns when the manifest has no hooks", () => {
    const { content, warnings } = generateCodexConfig(
      parseManifest({ version: 1, hooks: [] }),
    );
    expect(warnings.length).toBe(1);
    expect(warnings[0]).toMatch(/no hooks/);
    expect(content).toContain("Generated by harness apply --runtime codex");
  });

  it("escapes embedded double-quotes in TOML strings", () => {
    const { content } = generateCodexConfig(
      parseManifest({
        version: 1,
        hooks: [
          {
            name: "weird",
            event: "PreToolUse",
            match: 'has "quotes"',
            command: "/usr/bin/true",
            blocking: false,
            budget_ms: 1000,
          },
        ],
      }),
    );
    expect(content).toContain('matcher = "has \\"quotes\\""');
  });

  it("escapes raw control characters in nested command hooks", () => {
    const SOH = String.fromCharCode(0x01);
    const { content } = generateCodexConfig(
      parseManifest({
        version: 1,
        hooks: [
          {
            name: "controls",
            event: "PreToolUse",
            command: `/usr/bin/true\n${SOH}`,
            description: `line1\nline2${SOH}end`,
            blocking: false,
            budget_ms: 1000,
          },
        ],
      }),
    );
    expect(content).toContain('command = "/usr/bin/true\\n\\u0001"');
    // The emitted TOML basic-string carries no raw control chars.
    const commandLine = content
      .split("\n")
      .find((l) => l.includes('command = "/usr/bin/true'));
    expect(commandLine).toBeDefined();
    const controlRe = new RegExp("[\\u0000-\\u001f\\u007f]");
    expect(controlRe.test(commandLine!)).toBe(false);
  });

  it("pins the path_match/bash_match strip behaviour for Codex output (removed keys, stripped at load; no projection warning any more)", () => {
    const { warnings, content } = generateCodexConfig(
      parseManifest({
        version: 1,
        hooks: [
          {
            name: "with-filter",
            event: "PreToolUse",
            command: "/usr/bin/true",
            blocking: false,
            budget_ms: 1000,
            path_match: "src/**/*.ts",
            bash_match: "^git push",
          },
        ],
      }),
    );
    expect(warnings.some((w) => w.includes("path_match") || w.includes("bash_match"))).toBe(false);
    expect(content).toContain('command = "/usr/bin/true"');
    expect(content).not.toMatch(/path_match|bash_match/);
  });

  it("projects memory.router into a UserPromptSubmit hook (PR #203)", () => {
    // Codex parity with generate-settings.ts: per-prompt memory
    // augmentation must wire on both runtimes, otherwise a Codex
    // operator who uses memory-router would silently lose the feature.
    const { content } = generateCodexConfig(
      parseManifest({
        version: 1,
        memory: {
          directories: [],
          router: { command: ["memory-router-user-prompt-submit"] },
        },
      }),
    );
    expect(content).toContain("[[hooks.UserPromptSubmit]]");
    expect(content).toContain('command = "memory-router-user-prompt-submit"');
    expect(content).toContain("timeout = 5");
  });

  it("omits memory.router from codex config when enabled:false", () => {
    const { content } = generateCodexConfig(
      parseManifest({
        version: 1,
        memory: {
          directories: [],
          router: {
            command: ["memory-router-user-prompt-submit"],
            enabled: false,
          },
        },
      }),
    );
    expect(content).not.toContain("memory-router-user-prompt-submit");
    expect(content).not.toContain("memory:router");
  });
});
