import * as fs from "node:fs";
import * as os from "node:os";
import * as path from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { stringify as yamlStringify } from "yaml";
import {
  GENERATED_DIRNAME,
  MEMORY_BASENAME,
  OPENCODE_CONFIG_BASENAME,
  SETTINGS_BASENAME,
  apply,
} from "../../../src/cli/apply/index.js";
import { HarnessExitError } from "../../../src/cli/exit-codes.js";
import { SOLUTION_VERDICT_SIGNING_KEY_ENV } from "../../../src/cli/apply/generate-settings.js";
import { signingKeyPathFor } from "../../../src/runtime/approval-signing.js";

let tmpHome: string;

beforeEach(() => {
  tmpHome = fs.mkdtempSync(path.join(os.tmpdir(), "harness-apply-opencode-"));
});

afterEach(() => {
  fs.rmSync(tmpHome, { recursive: true, force: true });
});

function writeManifest(extra: Record<string, unknown> = {}): string {
  const manifest = {
    version: 1,
    tools: {
      mcp: [{ name: "agent-tasks", command: "agent-tasks-mcp-bridge" }],
      cli: [],
      skills: { enabled: [], source_dirs: [] },
      builtin: { known: [] },
    },
    memory: { directories: [] },
    hooks: [],
    policies: [],
    ...extra,
  };
  const target = path.join(tmpHome, "harness.yaml");
  fs.writeFileSync(target, yamlStringify(manifest));
  return target;
}

describe("apply --runtime opencode", () => {
  it("writes harness.generated/opencode/opencode.json in place of settings.json", async () => {
    writeManifest();
    const result = await apply({ homeDir: tmpHome, runtime: "opencode" });
    expect(result.outcome).toBe("applied");

    const opencodePath = path.join(tmpHome, GENERATED_DIRNAME, OPENCODE_CONFIG_BASENAME);
    const settingsPath = path.join(tmpHome, GENERATED_DIRNAME, SETTINGS_BASENAME);
    const memoryPath = path.join(tmpHome, GENERATED_DIRNAME, MEMORY_BASENAME);

    expect(fs.existsSync(opencodePath)).toBe(true);
    expect(fs.existsSync(settingsPath)).toBe(false);
    expect(fs.existsSync(memoryPath)).toBe(true);

    const config = fs.readFileSync(opencodePath, "utf8");
    expect(config).toContain("Generated by harness apply --runtime opencode");
    expect(config).toContain('"agent-tasks"');
    expect(config).toContain('"type": "local"');
    expect(config).toContain("agent-tasks-mcp-bridge");
  });

  it("default runtime keeps existing claude-code shape (settings.json present)", async () => {
    writeManifest();
    const result = await apply({ homeDir: tmpHome });
    expect(result.outcome).toBe("applied");

    const settingsPath = path.join(tmpHome, GENERATED_DIRNAME, SETTINGS_BASENAME);
    const opencodePath = path.join(tmpHome, GENERATED_DIRNAME, OPENCODE_CONFIG_BASENAME);
    expect(fs.existsSync(settingsPath)).toBe(true);
    expect(fs.existsSync(opencodePath)).toBe(false);
  });

  it("rejects --target with --runtime opencode (incompatible Claude Code surface)", async () => {
    writeManifest();
    const targetPath = path.join(tmpHome, "claude-settings.json");
    await expect(
      apply({ homeDir: tmpHome, runtime: "opencode", target: targetPath }),
    ).rejects.toBeInstanceOf(HarnessExitError);
  });

  it("a re-apply against the opencode output is no-op (byte-stable regeneration)", async () => {
    writeManifest();
    await apply({ homeDir: tmpHome, runtime: "opencode" });
    const second = await apply({ homeDir: tmpHome, runtime: "opencode" });
    expect(second.outcome).toBe("no-changes");
  });

  it("surfaces a warning when permission_profile is set under --runtime opencode (silent-drop guard)", async () => {
    writeManifest({
      policy_packs: [
        {
          name: "understanding-before-execution",
          config: { permission_profile: "safe-start" },
        },
      ],
    });
    const result = await apply({ homeDir: tmpHome, runtime: "opencode" });
    expect(result.outcome).toBe("applied");
    expect(
      result.warnings.some((w) => w.includes("permission") && w.includes("opencode")),
    ).toBe(true);
  });

  it("does not project policy-pack hooks into the opencode config, and warns", async () => {
    writeManifest({
      policy_packs: [{ name: "understanding-before-execution" }],
    });
    const result = await apply({ homeDir: tmpHome, runtime: "opencode" });
    expect(result.outcome).toBe("applied");

    const opencodePath = path.join(tmpHome, GENERATED_DIRNAME, OPENCODE_CONFIG_BASENAME);
    const config = fs.readFileSync(opencodePath, "utf8");
    expect(config).not.toContain("harness pack hook");
    expect(config).not.toContain("PreToolUse");
    expect(
      result.warnings.some(
        (w) => w.includes("hook(s)") && w.includes("no declarative hook wiring"),
      ),
    ).toBe(true);

    // instructions.md still ships, but its CONTENT is runtime-specific
    // (HIGH-F1, batch18 fix-round, task f34eb233): before this fix,
    // understanding-before-execution's buildInstructions() fell through
    // to the claude-code `else` branch under `--runtime opencode` and
    // falsely claimed its hooks were "wired into the harness-managed
    // settings.json", even though nothing is wired for opencode (no
    // settings.json exists, and packExpansion.hooks is never projected
    // into the opencode artefact -- asserted above via the "hook(s)...
    // no declarative hook wiring" warning). The inert
    // `instructions.length > 0` assertion this replaced would pass
    // whether or not that false claim was present.
    const instructions = fs.readFileSync(
      path.join(
        tmpHome,
        GENERATED_DIRNAME,
        "policy-packs",
        "understanding-before-execution",
        "instructions.md",
      ),
      "utf8",
    );
    expect(instructions).not.toContain(
      "hooks are wired into the harness-managed `settings.json`",
    );
    expect(instructions).toContain("not wired");
    expect(instructions).toContain("UNSUPPORTED");
  });

  it("marks post-merge-gate as UNSUPPORTED under --runtime opencode, in BOTH the instructions.md Runtime marker and the pack-level apply warning", async () => {
    writeManifest({
      policy_packs: [{ name: "post-merge-gate" }],
    });
    const result = await apply({ homeDir: tmpHome, runtime: "opencode" });
    expect(result.outcome).toBe("applied");

    // Pack-level warning (post-merge-gate.ts's resolve()): before this
    // fix, the runtime !== "claude-code" check was `runtime === "codex"`
    // only, so opencode silently got no warning at all even though this
    // pack (unlike understanding-before-execution) has no opencode OR
    // codex adapter and is fully inert under both.
    expect(
      result.warnings.some(
        (w) =>
          w.includes("policy_packs[post-merge-gate]") &&
          w.includes("no opencode adapter") &&
          w.includes("no declarative hook/event wiring"),
      ),
    ).toBe(true);

    // instructions.md's "## Runtime" section carries the same
    // UNSUPPORTED marker post-merge-gate already emits for codex,
    // mirrored for opencode.
    const instructions = fs.readFileSync(
      path.join(
        tmpHome,
        GENERATED_DIRNAME,
        "policy-packs",
        "post-merge-gate",
        "instructions.md",
      ),
      "utf8",
    );
    expect(instructions).toContain("opencode (UNSUPPORTED");
  });
});

// task 03a917fd/H1b: apply.ts's buildExpectedFiles now threads its own
// resolved `generatedDir` into generateOpencodeConfig's extras (mirroring
// the settings.json branch's equivalent generateSettingsWithWarnings call
// -- see that call site's comment for why THIS branch, unlike the
// settings.json one, is where the projection is actually observable:
// opencode's generated config file carries its `mcp` block verbatim,
// while settings.json never serializes mcpServers post-T-002). These
// tests exercise the real apply() pipeline end-to-end, not just the
// generate-settings.ts/generate-opencode-config.ts primitives (already
// unit-tested separately), so they double as the mutation-testable proof
// that apply.ts's generatedDir wiring is actually live.
describe("apply --runtime opencode — SOLUTION_VERDICT_SIGNING_KEY projection (task 03a917fd/H1b)", () => {
  function readOpencodeMcp(): Record<string, { environment?: Record<string, string> }> {
    const opencodePath = path.join(tmpHome, GENERATED_DIRNAME, OPENCODE_CONFIG_BASENAME);
    const jsonBody = fs
      .readFileSync(opencodePath, "utf8")
      .split("\n")
      .filter((l) => !l.startsWith("//"))
      .join("\n");
    return (JSON.parse(jsonBody) as { mcp: Record<string, { environment?: Record<string, string> }> })
      .mcp;
  }

  it("projects an absolute, real SOLUTION_VERDICT_SIGNING_KEY onto grounding-mcp in the generated opencode config", async () => {
    writeManifest({
      tools: {
        mcp: [{ name: "grounding-mcp", command: ["grounding-mcp-server"] }],
        cli: [],
        skills: { enabled: [], source_dirs: [] },
        builtin: { known: [] },
      },
    });
    const result = await apply({ homeDir: tmpHome, runtime: "opencode" });
    expect(result.outcome).toBe("applied");

    const expectedKeyPath = signingKeyPathFor(path.join(tmpHome, GENERATED_DIRNAME));
    expect(path.isAbsolute(expectedKeyPath)).toBe(true);
    const mcp = readOpencodeMcp();
    expect(mcp["grounding-mcp"]?.environment?.[SOLUTION_VERDICT_SIGNING_KEY_ENV]).toBe(
      expectedKeyPath,
    );
  });

  it("does not override an operator-declared SOLUTION_VERDICT_SIGNING_KEY", async () => {
    writeManifest({
      tools: {
        mcp: [
          {
            name: "grounding-mcp",
            command: ["grounding-mcp-server"],
            env: { SOLUTION_VERDICT_SIGNING_KEY: "/operator/own.key" },
          },
        ],
        cli: [],
        skills: { enabled: [], source_dirs: [] },
        builtin: { known: [] },
      },
    });
    const result = await apply({ homeDir: tmpHome, runtime: "opencode" });
    expect(result.outcome).toBe("applied");

    const mcp = readOpencodeMcp();
    expect(mcp["grounding-mcp"]?.environment?.[SOLUTION_VERDICT_SIGNING_KEY_ENV]).toBe(
      "/operator/own.key",
    );
  });
});
