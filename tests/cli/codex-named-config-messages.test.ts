// Printed commands that act on a Codex config name the config the call named.
//
// A call that names a Codex config (`--codex-config` for apply, `--config` for
// the gate) prints every recovery command with the same config, shell-quoted;
// a call that names none prints the bare command (the default
// ~/.codex/config.toml). Four site classes: installer refusals (reached
// through apply and through the gate), the install warning, the doctor's
// install hint, and apply's next-steps hint.

import * as fs from "node:fs";
import * as os from "node:os";
import * as path from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { stringify as yamlStringify } from "yaml";
import { generateCodexConfig } from "../../src/cli/apply/generate-codex-config.js";
import {
  CODEX_MANAGED_BEGIN,
  CODEX_MANAGED_END,
  CodexInstallRefusalError,
  planCodexConfigInstall,
  writeCodexConfigInstall,
} from "../../src/cli/apply/install-codex-config.js";
import { checkCodexLiveHooks } from "../../src/cli/doctor/hook-liveness.js";
import { codexGateDisable } from "../../src/cli/gate/codex-disable.js";
import { codexGateEnable } from "../../src/cli/gate/codex-enable.js";
import { codexSnapshotPath } from "../../src/cli/gate/codex-snapshot.js";
import { buildProgram } from "../../src/cli/index.js";
import { parseManifest } from "../../src/schema/index.js";

const INSTALL = "harness apply --runtime codex --install";
/** An install command in `text` that is not followed by the config flag. */
const BARE_INSTALL = /harness apply --runtime codex --install(?! --codex-config)/g;

let tmp: string;
/** A config path whose directory holds a space and a single quote. */
let spaced: string;
/** The same path as the shell word the printed command must carry. */
let spacedWord: string;
/** A config at the default place under a fake home. */
let defaultConfig: string;

beforeEach(() => {
  tmp = fs.mkdtempSync(path.join(fs.realpathSync(os.tmpdir()), "harness-named-config-"));
  spaced = path.join(tmp, "my codex's dir", "config.toml");
  spacedWord = `'${spaced.replace(/'/g, "'\\''")}'`;
  defaultConfig = path.join(tmp, ".codex", "config.toml");
});

afterEach(() => {
  fs.rmSync(tmp, { recursive: true, force: true });
});

function manifest() {
  return parseManifest({
    version: 1,
    hooks: [
      {
        name: "policy-pack:branch-protection:pre-tool-use",
        event: "PreToolUse",
        match: "apply_patch",
        command: "harness pack hook branch-protection --runtime codex",
        blocking: "hard",
        budget_ms: 5000,
      },
      {
        name: "hand-shell-guard",
        event: "PreToolUse",
        match: "Bash",
        command: "harness pack hook shell-guard --runtime codex",
        blocking: "hard",
        budget_ms: 5000,
      },
      {
        name: "hand-user-prompt-submit",
        event: "UserPromptSubmit",
        command: "/usr/bin/true",
        blocking: false,
        budget_ms: 5000,
      },
    ],
  });
}

const generatedContent = (): string => generateCodexConfig(manifest()).content;

function install(target: string): void {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  const plan = planCodexConfigInstall({
    configPath: target,
    generatedPath: "/gen/codex/config.toml",
    generatedContent: generatedContent(),
  });
  writeCodexConfigInstall(plan, { now: new Date("2026-10-01T00:00:00.000Z") });
}

function thrown(call: () => unknown): Error {
  try {
    call();
  } catch (err) {
    return err as Error;
  }
  throw new Error("expected the call to throw");
}

/** A block a foreign table splits in two: the installer refuses to guess. */
const SPLIT_BLOCK = [
  CODEX_MANAGED_BEGIN,
  "# Generated by harness apply --runtime codex.",
  "# harness hook: example-a (budget_ms=2000)",
  "[[hooks.PreToolUse]]",
  'hooks = [{ type = "command", command = "harness pack hook a", timeout = 2 }]',
  "",
  "[a-foreign-table-inserted-mid-block]",
  'value = "surprise"',
  "",
  "# harness hook: example-b (budget_ms=2000)",
  "[[hooks.Stop]]",
  'hooks = [{ type = "command", command = "harness pack hook b", timeout = 2 }]',
  CODEX_MANAGED_END,
  "",
].join("\n");

function planAt(opts: { configPath?: string; homeDir?: string }): CodexInstallRefusalError {
  const err = thrown(() =>
    planCodexConfigInstall({
      ...opts,
      generatedPath: "/gen/codex/config.toml",
      generatedContent: generatedContent(),
    }),
  );
  expect(err).toBeInstanceOf(CodexInstallRefusalError);
  return err as CodexInstallRefusalError;
}

describe("installer refusals reached through apply", () => {
  it("a named config with a space and a quote: the re-run command carries it, shell-quoted", () => {
    fs.mkdirSync(path.dirname(spaced), { recursive: true });
    fs.writeFileSync(spaced, SPLIT_BLOCK);
    const err = planAt({ configPath: spaced });
    expect(err.message).toContain(`\`${INSTALL} --codex-config ${spacedWord}\``);
    expect(err.message.match(BARE_INSTALL)).toBeNull();
    // The refusal still names the file it refused on.
    expect(err.configPath).toBe(spaced);
  });

  it("no named config: the bare command, no flag (the default ~/.codex/config.toml)", () => {
    fs.mkdirSync(path.dirname(defaultConfig), { recursive: true });
    fs.writeFileSync(defaultConfig, SPLIT_BLOCK);
    const err = planAt({ homeDir: tmp });
    expect(err.message).toContain(`\`${INSTALL}\``);
    expect(err.message).not.toContain("--codex-config");
  });

  it("the config the call named wins over the home directory's default", () => {
    // Both exist; only the named one is split. The refusal is about it and prints it.
    fs.mkdirSync(path.dirname(spaced), { recursive: true });
    fs.writeFileSync(spaced, SPLIT_BLOCK);
    install(defaultConfig);
    const err = planAt({ configPath: spaced, homeDir: tmp });
    expect(err.message).toContain(`--codex-config ${spacedWord}`);
    expect(err.message).not.toContain(defaultConfig);
  });
});

describe("installer refusals reached through the gate", () => {
  /** A config whose block lost its END marker. */
  function writeUnclosed(target: string): void {
    install(target);
    fs.writeFileSync(target, fs.readFileSync(target, "utf8").replace(CODEX_MANAGED_END, "# not the end"));
  }

  it("--config with a space: the re-run command carries it as --codex-config, shell-quoted", () => {
    writeUnclosed(spaced);
    const err = thrown(() => codexGateDisable({ configPath: spaced, matcher: "apply_patch" }));
    expect(err.message).toContain(`re-run \`${INSTALL} --codex-config ${spacedWord}\``);
    expect(err.message.match(BARE_INSTALL)).toBeNull();
  });

  it("no --config: the bare command", () => {
    writeUnclosed(defaultConfig);
    const err = thrown(() => codexGateDisable({ homeDir: tmp, matcher: "apply_patch" }));
    expect(err.message).toContain(`re-run \`${INSTALL}\``);
    expect(err.message).not.toContain("--codex-config");
  });

  it("a block without its BEGIN fence, reached by an enable: the same flag", () => {
    install(spaced);
    codexGateDisable({ configPath: spaced, matcher: "apply_patch", now: new Date("2026-10-02T10:00:00.000Z") });
    fs.writeFileSync(spaced, fs.readFileSync(spaced, "utf8").replace(CODEX_MANAGED_BEGIN, "# not the begin"));
    const err = thrown(() => codexGateEnable({ configPath: spaced }));
    expect(err.message).toContain(`${INSTALL} --codex-config ${spacedWord}`);
    expect(err.message.match(BARE_INSTALL)).toBeNull();
  });

  it("a version 2 snapshot: the re-run command carries the flag, bare without one", () => {
    for (const named of [true, false]) {
      const target = named ? spaced : defaultConfig;
      install(target);
      const d = codexGateDisable({
        ...(named ? { configPath: target } : { homeDir: tmp }),
        matcher: "apply_patch",
        now: new Date("2026-10-02T10:00:00.000Z"),
      });
      if (d.mode !== "remove") throw new Error("expected a snapshot");
      const snap = JSON.parse(fs.readFileSync(d.snapshotPath, "utf8")) as Record<string, unknown>;
      fs.writeFileSync(d.snapshotPath, JSON.stringify({ ...snap, version: 2 }));
      // Both verbs read the live snapshot first.
      const where = named ? { configPath: target } : { homeDir: tmp };
      for (const err of [
        thrown(() => codexGateEnable(where)),
        thrown(() => codexGateDisable({ ...where, matcher: "Bash" })),
      ]) {
        expect(err.message).toContain("version 2 Codex gate snapshot");
        if (named) {
          expect(err.message).toContain(`\`${INSTALL} --codex-config ${spacedWord}\` to rewrite the block`);
        } else {
          expect(err.message).toContain(`\`${INSTALL}\` to rewrite the block`);
          expect(err.message).not.toContain("--codex-config");
        }
      }
    }
  });
});

describe("the install warning for a snapshot it cannot read", () => {
  function warningFor(target: string, named: boolean): string {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, "");
    const junk = codexSnapshotPath(target, new Date("2026-10-02T00:30:00.000Z"));
    fs.writeFileSync(junk, "{ not json");
    const plan = planCodexConfigInstall({
      ...(named ? { configPath: target } : { homeDir: tmp }),
      generatedPath: "/gen/codex/config.toml",
      generatedContent: generatedContent(),
    });
    const result = writeCodexConfigInstall(plan, { now: new Date("2026-10-03T00:00:00.000Z") });
    expect(result.snapshotWarnings).toHaveLength(1);
    return result.snapshotWarnings![0]!;
  }

  it("names the gate command for the Codex runtime and the call's config, shell-quoted", () => {
    const w = warningFor(spaced, true);
    expect(w).toContain(`\`harness gate enable --runtime codex --config ${spacedWord}\` will refuse on it`);
  });

  it("names the Codex runtime without a flag when the call named no config", () => {
    const w = warningFor(defaultConfig, false);
    expect(w).toContain("`harness gate enable --runtime codex` will refuse on it");
    expect(w).not.toContain("--config");
  });
});

describe("the doctor's install hint", () => {
  it("a config other than the default carries --codex-config, shell-quoted; the default prints none", () => {
    fs.mkdirSync(path.dirname(spaced), { recursive: true });
    const elsewhere = path.join(tmp, "home", ".codex", "config.toml");
    // The config is absent: the finding is the hint.
    const named = checkCodexLiveHooks(manifest(), spaced, { gateDefaultPath: elsewhere });
    expect(named.entries.map((e) => e.message).join("\n")).toContain(
      `run \`${INSTALL} --codex-config ${spacedWord}\``,
    );
    const atDefault = checkCodexLiveHooks(manifest(), spaced, { gateDefaultPath: spaced });
    const plain = atDefault.entries.map((e) => e.message).join("\n");
    expect(plain).toContain(`run \`${INSTALL}\``);
    expect(plain).not.toContain("--codex-config");
  });
});

describe("the doctor's message for a version 2 gate snapshot", () => {
  it("repeats the config the doctor reads when it is not the default; the default prints the bare command", () => {
    install(spaced);
    const d = codexGateDisable({ configPath: spaced, matcher: "apply_patch", now: new Date("2026-10-02T10:00:00.000Z") });
    if (d.mode !== "remove") throw new Error("expected a snapshot");
    const snap = JSON.parse(fs.readFileSync(d.snapshotPath, "utf8")) as Record<string, unknown>;
    fs.writeFileSync(d.snapshotPath, JSON.stringify({ ...snap, version: 2 }));
    const messages = (gateDefaultPath: string): string =>
      checkCodexLiveHooks(manifest(), spaced, { gateDefaultPath })
        .entries.map((e) => e.message)
        .join("\n");
    expect(messages(defaultConfig)).toContain(`\`${INSTALL} --codex-config ${spacedWord}\` to rewrite the block`);
    const atDefault = messages(spaced);
    expect(atDefault).toContain(`\`${INSTALL}\` to rewrite the block`);
    expect(atDefault).not.toContain("--codex-config");
  });
});

describe("apply's next-steps hint, through the CLI", () => {
  async function applyOutput(extra: string[]): Promise<string> {
    const manifestPath = path.join(tmp, "harness.yaml");
    fs.writeFileSync(
      manifestPath,
      yamlStringify({
        version: 1,
        tools: { mcp: [], cli: [], skills: { enabled: [], source_dirs: [] }, builtin: { known: [] } },
        memory: { directories: [] },
        hooks: [],
        policies: [],
        policy_packs: [{ name: "branch-protection" }],
      }),
    );
    let out = "";
    const program = buildProgram({
      stdout: (s: string) => {
        out += s;
      },
      stderr: () => {},
    });
    await program.parseAsync(["apply", "--config", manifestPath, "--runtime", "codex", ...extra], {
      from: "user",
    });
    return out;
  }

  it("--codex-config with a space, no --install: the printed install command repeats it, shell-quoted", async () => {
    const out = await applyOutput(["--codex-config", spaced]);
    expect(out).toContain(`Install the harness-managed hook block into ${spaced}:`);
    expect(out).toContain(`  ${INSTALL} --codex-config ${spacedWord}\n`);
    expect(out).not.toContain("~/.codex/config.toml");
  });

  it("no --codex-config: the default text, bare command", async () => {
    const out = await applyOutput([]);
    expect(out).toContain("Install the harness-managed hook block into ~/.codex/config.toml:");
    expect(out).toContain(`  ${INSTALL}\n`);
    expect(out).not.toContain(`${INSTALL} --codex-config`);
  });
});
